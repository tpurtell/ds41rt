"""Assemble the v10 TP3 campaign manifests and docs from canonical sources.

v10 reporting has two stages:

  1. Each lane writes its own manifest next to its raw evidence (for the native
     arm, `runs/v10-native-tp3ep1/manifest.json`). That lane manifest is the
     durable record: raw paths, measured values, limitations and provenance.
  2. This bootstrap assembles the published campaign documents from those
     canonical manifests:

       docs/release-v10-tp3-official-1x-3spark.md
       docs/release-v10-tp3-exl3-compact-1x-3spark.md
       docs/release-v10-tp3-campaign-status.md

This script does not invent measurements and never launches anything; it only
writes manifests and invokes the CPU-only renderer.

A lane that has not been measured is emitted as an explicit PRE-MEASUREMENT
BOOTSTRAP manifest (`bootstrap_only: true`) with every family pending. This
script will never overwrite a canonical manifest that already carries raw
evidence, and it will not overwrite a committed measured report whose raw
evidence is absent from this checkout, so re-running it cannot erase a
measurement. Re-run it after a lane publishes its manifest and the same
documents carry the measured values.

Usage:
  runs/v10-tp3/generate-docs.py [--check]
"""
